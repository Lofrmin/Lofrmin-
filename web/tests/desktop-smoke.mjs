import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { ensureFakeCamera } from './fake-camera.mjs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { _electron } = require('playwright-core');
mkdirSync('artifacts', { recursive: true });
const env = { ...process.env, NEURODESK_COFFEE_DEMO: '0', NEURODESK_TEST: '1' }; delete env.ELECTRON_RUN_AS_NODE;
const packaged = process.env.NEURODESK_TEST_EXECUTABLE;
const userData = resolve('.runtime/test-userdata-smoke'); mkdirSync(userData, { recursive: true });
const fakeCamera = ensureFakeCamera();
const electron = await _electron.launch({ executablePath: packaged || require('electron'), args: ['--no-sandbox', `--user-data-dir=${userData}`, '--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', `--use-file-for-fake-video-capture=${fakeCamera}`, ...(packaged ? [] : ['.'])], env, timeout: 60000 });
const errors = [];
const runtimeLog = [];
electron.process().stderr?.on('data', (data) => { runtimeLog.push(data.toString()); });
electron.on('window', (page) => {
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (['error', 'warning'].includes(message.type())) runtimeLog.push(`${page.url()}: ${message.text()}\n`); });
});
try {
  await electron.firstWindow();
  for (let i = 0; i < 300 && !electron.windows().some((p) => p.url().endsWith('/index.html')); i++) await new Promise((resolve) => setTimeout(resolve, 100));
  const pages = electron.windows();
  const panel = pages.find((p) => p.url().includes('index.html'));
  const pet = pages.find((p) => p.url().includes('pet.html'));
  const monitor = pages.find((p) => p.url().includes('monitor.html'));
  assert.ok(panel && pet && monitor, 'three independent native windows');
  await panel.waitForFunction(() => window.neuro?.nativeSnapshot?.running && window.neuro.nativeSnapshot.fps > 0, undefined, { timeout: 60000 });
  console.log('Initial window visibility:', await electron.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((w) => w.webContents.getURL().endsWith('/index.html')).isVisible()));
  await pet.click('#pet-open');
  await panel.waitForFunction(() => document.hasFocus());
  await panel.click('[data-view="companion"]');
  await panel.locator('.pet-card').first().click();
  await panel.waitForSelector('#stage .pet-body[data-live2d="ready"]', { timeout: 60000 });
  await panel.screenshot({ path: 'artifacts/desktop-overview.png', fullPage: true });
  const before = await panel.evaluate(() => window.neuro.nativeSnapshot.at);
  await electron.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((w) => w.webContents.getURL().endsWith('/index.html')).close());
  await panel.waitForFunction((t) => window.neuro.nativeSnapshot.at > t + 1500, before);
  assert.equal(await panel.evaluate(() => window.neuro.nativeSnapshot.running), true, 'camera continues after panel close');
  await pet.click('#pet-stage');
  await panel.waitForFunction(() => document.hasFocus());
  const petBounds = () => electron.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((w) => w.webContents.getURL().endsWith('/pet.html')).getBounds());
  const oldBounds = await petBounds();
  const stage = await pet.locator('#pet-stage').boundingBox();
  await pet.mouse.move(stage.x + stage.width / 2, stage.y + stage.height / 2);
  await pet.mouse.down();
  await pet.mouse.move(stage.x + stage.width / 2 - 35, stage.y + stage.height / 2 - 25, { steps: 3 });
  await pet.mouse.up();
  const newBounds = await petBounds();
  assert.ok(newBounds.x < oldBounds.x || newBounds.y < oldBounds.y, 'pet can be dragged on the desktop');
  await pet.click('#pet-open');
  await panel.click('#btn-start');
  await panel.waitForFunction(() => window.neuro.nativeSnapshot.status === 'paused');
  await panel.click('#btn-start');
  await panel.waitForFunction(() => window.neuro.nativeSnapshot.running);
  await panel.click('[data-view="companion"]');
  await panel.locator('.pet-card').nth(2).click();
  await pet.waitForFunction(() => document.querySelector('.pet').dataset.pet === 'soot');
  await panel.click('[data-view="desk"]');
  await panel.click('#coffee-go');
  await panel.waitForSelector('.coffee-store');
  assert.equal(await panel.locator('.coffee-product button:enabled').count(), 0);
  await panel.screenshot({ path: 'artifacts/desktop-coffee.png', fullPage: true });
  await panel.click('#coffee-close');
  await monitor.evaluate(() => window.neuroDesktop.publish({ running: true, status: 'running', state: 'tired', focus: 50, fatigue: 65, source: '本机测试注入', at: Date.now() }));
  await panel.waitForSelector('#coffee-dialog[open]');
  await panel.click('#coffee-close');
  await pet.screenshot({ path: 'artifacts/desktop-pet.png', omitBackground: true });
  assert.deepEqual(errors, []);
  console.log('Desktop passed: hidden engine, automatic sensing, pet opens panel, draggable pet, panel close preserves camera, pause/resume, pet sync, sample order blocked, native fatigue popup.');
} catch (error) {
  console.error('Windows:', electron.windows().map((p) => p.url()));
  console.error('Runtime:', runtimeLog.join('').slice(-6000));
  console.error('Page errors:', errors);
  const currentPanel = electron.windows().find((p) => p.url().endsWith('/index.html'));
  if (currentPanel) console.error('Diagnostics:', await currentPanel.evaluate(() => ({ snapshot: window.neuro?.nativeSnapshot, pet: localStorage.getItem('nd-pet'), stage: document.querySelector('#stage .pet')?.outerHTML.slice(-1000) })));
  throw error;
} finally { await electron.close(); }
